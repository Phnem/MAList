package com.example.myapplication.ui.home

/** Что печатаем вместо количества, когда источник его не знает. */
const val UnknownCountText = "N/A"

/**
 * Количество серий или глав для карточки выдачи поиска.
 *
 * Источники — чаще всего Shikimori — на неизвестном количестве отдают 0. Печатать «0 eps» нельзя:
 * это читается как «серий нет», хотя источник просто не знает их числа. Ноль и «неизвестно» тут
 * разные вещи, и наружу они разными и выходят.
 *
 * Отдельным файлом без зависимостей от Compose — чтобы функция была покрываема обычным
 * JVM-тестом (см. `SearchResultCountTextTest`).
 *
 * Внимание: на **хранение** это не влияет. `AddFromApiUseCase` по-прежнему сохраняет
 * `episodes.coerceAtLeast(1)`, то есть в БД неизвестное количество превращается в 1 серию.
 * Так решено пользователем на интервью 2026-07-29 (решение D-4 в MASTER_PLAN) — правка
 * сознательно ограничена представлением.
 */
fun searchResultCountText(count: Int?, unitLabel: String): String =
    if (count == null || count <= 0) UnknownCountText else "$count $unitLabel"
