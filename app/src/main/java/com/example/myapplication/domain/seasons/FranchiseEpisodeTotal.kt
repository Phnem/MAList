package com.example.myapplication.domain.seasons

/**
 * Сколько серий во франшизе всего — знаменатель прогресса на карточке.
 *
 * Числитель считается сквозной нумерацией по франшизе (серии сезонов до текущего плюс номер
 * текущей серии, см. `HomeViewModel.watchedEpisodes`), а [storedEpisodes] описывает ОДИН сезон.
 * Две разные шкалы в одной строке и давали «просмотрено 15 / 12»: на втором сезоне числитель
 * перерастал знаменатель. Здесь обе шкалы сводятся к франшизной.
 *
 * Расклад обязан быть тем же, по которому считался числитель, иначе шкалы разъедутся снова.
 *
 * Нерешённый расклад — это неизвестность, а не ноль: пустая цепочка возвращает прежнее
 * сохранённое значение, и односезонные тайтлы ведут себя ровно как раньше.
 *
 * У онгоинга сумма будет расти со временем: [SeasonInfo.episodes] — это «доступно сейчас»,
 * а не «анонсировано». Это осознанно, знаменатель обязан жить в той же шкале, что числитель.
 */
fun franchiseEpisodeTotal(layout: SeasonEpisodesEntry?, storedEpisodes: Int): Int {
    val franchiseSum = layout?.seasons?.sumOf { it.episodes } ?: 0
    return if (franchiseSum > 0) franchiseSum else storedEpisodes
}
